type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string) => string;
  isHydrated: boolean;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return value;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("pt");
  const [isHydrated, setIsHydrated] = useState(false);

  useEffect(() => {
    const stored = localStorage.getItem(LOCALE_KEY);
    const newLocale = stored === "pt" || stored === "en" || stored === "am" ? stored : "pt";

    if (newLocale !== locale) {
      setLocaleState(newLocale);
    }
    setIsHydrated(true);
  }, []);

  useEffect(() => {
    if (typeof document === "undefined") {
      return;
    }
    document.documentElement.lang = locale;
    localStorage.setItem(LOCALE_KEY, locale);
  }, [locale]);

  const setLocale = useCallback((next: Locale) => setLocaleState(next), []);

  const t = useCallback(
    (key: string) => {
      const raw =
        DICTS[locale][key] ??
        DICTS.pt[key] ??
        DICTS.en[key] ??
        (locale === "en" ? "Text unavailable" : locale === "am" ? "የጽሑፍ ትርጉም የለም" : "Texto indisponível");
      return raw
        .replaceAll("{brand}", BRAND_NAME)
        .replaceAll("{supportEmail}", SUPPORT_EMAIL);
    },
    [locale],
  );

  const i18nValue = useMemo<I18nContextValue>(
    () => ({ locale, setLocale, t, isHydrated }),
    [locale, setLocale, t, isHydrated],
  );

  return (
    <I18nContext.Provider value={i18nValue}>{children}</I18nContext.Provider>
  );
}
